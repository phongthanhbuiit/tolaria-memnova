import { expect, test } from '@playwright/test'

test('migrated daily goal preserves mouse editing, ref focus, Enter, Escape and blur', async ({ page }) => {
  await page.goto('/tests/fixtures/form-migration.html')
  const action = page.getByTitle('Click to edit daily goal')
  await action.click()
  const input = page.getByRole('spinbutton', { name: 'Edit daily goal' })
  await expect(input).toBeFocused()
  await expect(input).toHaveAttribute('min', '1')
  await expect(input).toHaveAttribute('max', '500')
  await input.fill('35')
  await input.press('Enter')
  await expect(action).toHaveText('35')
  await action.click()
  await input.fill('99')
  await input.press('Escape')
  await expect(action).toHaveText('35')
  await action.click()
  await input.fill('42')
  await page.getByTestId('note-icon-display').click()
  await expect(action).toHaveText('42')
})

test('migrated emoji choice retains click and keyboard activation with the same value', async ({ page }) => {
  await page.goto('/tests/fixtures/form-migration.html?surface=emoji')
  await page.getByPlaceholder('Search emoji by name...').fill('rocket')
  const choice = page.getByRole('button', { name: 'Choose 🚀', exact: true })
  await choice.click()
  await expect(page.locator('output')).toHaveText('🚀')
  await page.getByPlaceholder('Search emoji by name...').fill('turtle')
  const turtle = page.getByRole('button', { name: 'Choose 🐢', exact: true })
  await turtle.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('output')).toHaveText('🐢')
})
